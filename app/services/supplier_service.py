"""Supplier Service — CRUD for the `suppliers` procurement master.

Tenant-scoped via app/core/tenant.py (owner `user_id` + optional `branch_id`),
mirroring `purchase_orders`. `supplier_code` is auto-generated by the DB
(`suppliers_code_seq` default → SUP-000001, ...) so it is always unique and
never client-supplied.

`current_outstanding` is a calculated field (opening_balance at creation time;
future ledger integration will maintain it) and is NEVER settable via the API.
"""
from typing import Optional

from app.core.auth import UserContext
from app.core.database import get_connection
from app.core.tenant import tenant_where_clause
from app.core.exceptions import NotFoundError, ValidationError
from app.core.logging import get_logger

logger = get_logger(__name__)

VALID_STATUSES = {"active", "inactive"}
VALID_PAYMENT_TERMS = {"cash", "credit", "advance"}
VALID_CATEGORIES = {
    "vegetables", "dairy", "meat_poultry", "seafood", "grocery",
    "beverages", "packaging", "cleaning_supplies", "other",
}

# Columns a client is allowed to write on create/update. Excludes id, user_id,
# restaurant_id, supplier_code, current_outstanding and timestamps.
_MUTABLE_COLUMNS = {
    "supplier_name", "business_name", "contact_person", "mobile",
    "alternate_phone", "email", "address_line1", "address_line2",
    "city", "state", "country", "pincode", "gstin", "pan", "fssai_license",
    "category", "min_order_value", "lead_time_days", "is_preferred",
    "payment_terms", "credit_period_days", "credit_limit", "opening_balance",
    "bank_name", "account_number", "ifsc", "upi_id", "status", "notes",
    "branch_id",
}

# Explicit insert order so create() stays readable and matches the migration.
_INSERT_COLUMNS = [
    "user_id", "restaurant_id", "branch_id",
    "supplier_name", "business_name", "contact_person", "mobile",
    "alternate_phone", "email",
    "address_line1", "address_line2", "city", "state", "country", "pincode",
    "gstin", "pan", "fssai_license",
    "category", "min_order_value", "lead_time_days", "is_preferred",
    "payment_terms", "credit_period_days", "credit_limit", "opening_balance",
    "current_outstanding",
    "bank_name", "account_number", "ifsc", "upi_id",
    "status", "notes",
]


class SupplierService:

    @staticmethod
    def _owner_id(user: UserContext) -> str:
        return user.owner_id if user.is_branch_user else user.user_id

    def _validate_business_fields(self, data: dict) -> None:
        """Enum-level validation enforced server-side (belt-and-braces on top
        of the router's Pydantic validators, and the DB CHECK constraints)."""
        status = data.get("status")
        if status is not None and status not in VALID_STATUSES:
            raise ValidationError(
                f"Invalid status. Must be one of: {', '.join(sorted(VALID_STATUSES))}"
            )
        terms = data.get("payment_terms")
        if terms is not None and terms not in VALID_PAYMENT_TERMS:
            raise ValidationError(
                f"Invalid payment_terms. Must be one of: {', '.join(sorted(VALID_PAYMENT_TERMS))}"
            )
        category = data.get("category")
        if category is not None and category not in VALID_CATEGORIES:
            raise ValidationError(
                f"Invalid category. Must be one of: {', '.join(sorted(VALID_CATEGORIES))}"
            )

    # ── Read ──────────────────────────────────────────────────────────────
    async def list_suppliers(
        self, user: UserContext, *,
        status: Optional[str] = None,
        supplier_name: Optional[str] = None,
        mobile: Optional[str] = None,
        gstin: Optional[str] = None,
        search: Optional[str] = None,
        limit: int = 50, offset: int = 0,
    ) -> dict:
        clause, params = tenant_where_clause(user)
        where = f"{clause} AND deleted_at IS NULL"

        if status:
            params.append(status)
            where += f" AND status = ${len(params)}"
        if supplier_name:
            params.append(f"%{supplier_name}%")
            where += f" AND supplier_name ILIKE ${len(params)}"
        if mobile:
            params.append(f"%{mobile}%")
            where += f" AND mobile ILIKE ${len(params)}"
        if gstin:
            params.append(gstin.upper())
            where += f" AND upper(gstin) = ${len(params)}"
        if search:
            params.append(f"%{search}%")
            n = len(params)
            where += (
                f" AND (supplier_name ILIKE ${n} OR business_name ILIKE ${n}"
                f" OR contact_person ILIKE ${n} OR mobile ILIKE ${n}"
                f" OR email ILIKE ${n} OR supplier_code ILIKE ${n})"
            )

        async with get_connection() as conn:
            total = await conn.fetchval(
                f"SELECT COUNT(*) FROM suppliers WHERE {where}", *params
            )
            rows_params = params + [limit, offset]
            rows = await conn.fetch(
                f"SELECT * FROM suppliers WHERE {where} "
                f"ORDER BY created_at DESC LIMIT ${len(rows_params)-1} OFFSET ${len(rows_params)}",
                *rows_params,
            )
        return {
            "items": [dict(r) for r in rows],
            "total": int(total or 0),
            "limit": limit,
            "offset": offset,
        }

    async def get_supplier(self, user: UserContext, supplier_id: str) -> dict:
        clause, params = tenant_where_clause(user)
        params.append(supplier_id)
        async with get_connection() as conn:
            row = await conn.fetchrow(
                f"SELECT * FROM suppliers WHERE {clause} "
                f"AND id = ${len(params)}::uuid AND deleted_at IS NULL",
                *params,
            )
        if not row:
            raise NotFoundError("Supplier", supplier_id)
        return dict(row)

    # ── Write ─────────────────────────────────────────────────────────────
    async def create_supplier(self, user: UserContext, data: dict) -> dict:
        self._validate_business_fields(data)

        name = (data.get("supplier_name") or "").strip()
        mobile = (data.get("mobile") or "").strip()
        if not name:
            raise ValidationError("supplier_name is required")
        if not mobile:
            raise ValidationError("mobile is required")

        opening_balance = data.get("opening_balance") or 0

        values = {
            "user_id": self._owner_id(user),
            "restaurant_id": user.restaurant_id,
            "branch_id": data.get("branch_id") or user.branch_id,
            "supplier_name": name,
            "business_name": data.get("business_name"),
            "contact_person": data.get("contact_person"),
            "mobile": mobile,
            "alternate_phone": data.get("alternate_phone"),
            "email": data.get("email"),
            "address_line1": data.get("address_line1"),
            "address_line2": data.get("address_line2"),
            "city": data.get("city"),
            "state": data.get("state"),
            "country": data.get("country") or "India",
            "pincode": data.get("pincode"),
            "gstin": data.get("gstin"),
            "pan": data.get("pan"),
            "fssai_license": data.get("fssai_license"),
            "category": data.get("category"),
            "min_order_value": data.get("min_order_value") or 0,
            "lead_time_days": data.get("lead_time_days"),
            "is_preferred": bool(data.get("is_preferred") or False),
            "payment_terms": data.get("payment_terms") or "cash",
            "credit_period_days": data.get("credit_period_days") or 0,
            "credit_limit": data.get("credit_limit") or 0,
            "opening_balance": opening_balance,
            "current_outstanding": opening_balance,
            "bank_name": data.get("bank_name"),
            "account_number": data.get("account_number"),
            "ifsc": data.get("ifsc"),
            "upi_id": data.get("upi_id"),
            "status": data.get("status") or "active",
            "notes": data.get("notes"),
        }

        cols = _INSERT_COLUMNS
        placeholders = []
        params = []
        for i, col in enumerate(cols, start=1):
            if col in ("restaurant_id", "branch_id"):
                placeholders.append(f"${i}::uuid")
            else:
                placeholders.append(f"${i}")
            params.append(values[col])

        async with get_connection() as conn:
            row = await conn.fetchrow(
                f"INSERT INTO suppliers ({', '.join(cols)}) "
                f"VALUES ({', '.join(placeholders)}) RETURNING *",
                *params,
            )
        logger.info("supplier_created", supplier_id=str(row["id"]), user_id=values["user_id"])
        return dict(row)

    async def update_supplier(self, user: UserContext, supplier_id: str, data: dict) -> dict:
        """Apply a partial (PATCH) or full (PUT) update.

        Only whitelisted columns are writable; `current_outstanding`,
        `supplier_code` and tenant keys can never be set by the client.
        """
        fields = {k: v for k, v in data.items() if k in _MUTABLE_COLUMNS}
        if not fields:
            raise ValidationError("no fields to update")

        self._validate_business_fields(fields)

        if "supplier_name" in fields:
            name = (fields["supplier_name"] or "").strip()
            if not name:
                raise ValidationError("supplier_name cannot be empty")
            fields["supplier_name"] = name
        if "mobile" in fields:
            mob = (fields["mobile"] or "").strip()
            if not mob:
                raise ValidationError("mobile cannot be empty")
            fields["mobile"] = mob

        clause, params = tenant_where_clause(user)  # params: [user_id] (+ branch_id)
        sets = []
        idx = len(params) + 1
        for col, val in fields.items():
            if col == "branch_id":
                sets.append(f"branch_id = ${idx}::uuid")
            else:
                sets.append(f"{col} = ${idx}")
            params.append(val)
            idx += 1
        sets.append("updated_at = NOW()")
        params.append(supplier_id)

        async with get_connection() as conn:
            row = await conn.fetchrow(
                f"UPDATE suppliers SET {', '.join(sets)} "
                f"WHERE {clause} AND id = ${idx}::uuid AND deleted_at IS NULL "
                f"RETURNING *",
                *params,
            )
        if not row:
            raise NotFoundError("Supplier", supplier_id)
        logger.info("supplier_updated", supplier_id=supplier_id, fields=list(fields.keys()))
        return dict(row)

    async def delete_supplier(self, user: UserContext, supplier_id: str) -> dict:
        """Soft-delete (deactivate) a supplier. History is preserved."""
        clause, params = tenant_where_clause(user)
        params.append(supplier_id)
        async with get_connection() as conn:
            row = await conn.fetchrow(
                f"UPDATE suppliers "
                f"SET deleted_at = NOW(), status = 'inactive', updated_at = NOW() "
                f"WHERE {clause} AND id = ${len(params)}::uuid AND deleted_at IS NULL "
                f"RETURNING id",
                *params,
            )
        if not row:
            raise NotFoundError("Supplier", supplier_id)
        logger.info("supplier_deleted", supplier_id=supplier_id)
        return {"deleted": True, "id": supplier_id}
